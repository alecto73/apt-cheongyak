# 특례시·통합시의 일반구는 미분양 통계 단위(시)로 합친다.
# "수원시장안구" 처럼 '<시>+<구>' 로 붙어 있는 지도 원본 명칭을 자른다.
def collapse_gu(name: str) -> str:
    """수원시장안구 -> 수원시, 창원시마산합포구 -> 창원시."""
    idx = name.find("시")
    if idx > 0 and idx < len(name) - 1 and name.endswith("구"):
        return name[: idx + 1]
    return name


